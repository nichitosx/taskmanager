"""Версия программы — одно место, откуда её берут все остальные.

Раньше вместо версии показывался отпечаток коммита: сорок символов, которые
человеку ничего не говорят. Теперь номер обычный, из трёх частей:

* первая меняется, когда работать с программой приходится по-новому;
* вторая — когда появляется заметная возможность;
* третья — когда что-то починили или подправили.

Файл читает и ``update.py``, причём текстом, а не импортом: ему нужно узнать
версию скачанных файлов, ещё не ставших программой.
"""

from __future__ import annotations

from datetime import date

VERSION = "1.1.0"
RELEASED = "2026-09-11"


def released_date() -> date | None:
    """Дата сборки. None, если её забыли или записали криво."""
    try:
        return date.fromisoformat(RELEASED)
    except (ValueError, TypeError):
        return None


def describe() -> str:
    """Человеческая подпись версии: «1.0.0 от 11.09.2026»."""
    when = released_date()
    return "%s от %s" % (VERSION, when.strftime("%d.%m.%Y")) if when else VERSION
